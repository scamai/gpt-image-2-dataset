# ── vision classification prompt (used by Gemini review) ─────────────────────

CLASSIFY_PROMPT = """\
You are curating a research dataset of images generated by GPT-image-2 (OpenAI's \
image generation model, released April 2026).

Tweet text (use as supporting context):
{tweet_text}

Classify the attached image into exactly one of these labels:

"confirmed" — A standalone image that was generated by GPT-image-2 / ChatGPT's image \
generation feature. The tweet text is consistent with this (may mention "made with ChatGPT", \
a prompt used, etc.). The image content itself looks like AI-generated art, illustration, \
or photo-realistic AI output.

"rejected" — Does NOT belong in this dataset. Reject for any of:
  (1) Side-by-side comparison grid showing multiple AI models
  (2) Screenshot of the ChatGPT or OpenAI interface / generation UI
  (3) Promotional graphic or feature matrix listing multiple AI tools
  (4) Screenshot of a news article or tweet discussing GPT-image-2
  (5) Meme, reaction image, or joke image about GPT-image-2
  (6) Real photograph clearly unrelated to AI generation
  (7) Image that is primarily text, logos, or interface elements

"uncertain" — Could plausibly be GPT-image-2 output but you are not confident. Use \
when signals are mixed, the image is ambiguous, or there is insufficient evidence.

Be conservative: prefer "uncertain" over "confirmed" when evidence is weak.

Respond ONLY with valid JSON on a single line, no other text:
{{"label": "confirmed|rejected|uncertain", "confidence": "high|medium|low", "reason": "one sentence"}}"""


# ── helpers ───────────────────────────────────────────────────────────────────

def _result(record: dict, label: str, reason: str, confidence: str) -> dict:
    return {
        **record,
        "classification": label,
        "classification_reason": reason,
        "classification_confidence": confidence,
        "classified_at": datetime.now(timezone.utc).isoformat(),
    }


def classify_by_metadata(record: dict) -> dict:
    """
    Classify one record using tweet text heuristics only.

    Returns confirmed / rejected / uncertain with a reason string.

    Rule priority (first match wins):
      1. Comparison grid (vs + another model)     → rejected
      2. Promotional (3+ AI tool names listed)    → rejected
      3. Announcement / news language             → rejected
      4. Explicit creation language               → confirmed
      5. Prompt shared in tweet                   → confirmed
      6. Personal creation language               → confirmed (medium confidence)
      7. Everything else                          → uncertain
    """
    text = record.get("text", "")
    tl = text.lower()

    # ── reject: comparison grid ───────────────────────────────────────────────
    has_vs = bool(re.search(r"\bvs\.?\b|\bversus\b", tl))
    has_cmp_char = bool(re.search(r"比較|对比|対決|対比", text))
    mentions_other = any(m in tl for m in _OTHER_MODELS)

    if (has_vs or has_cmp_char) and mentions_other:
        return _result(record, "rejected",
                       "comparison tweet (VS language + another model name)", "high")

    # ── reject: promotional listing ───────────────────────────────────────────
    tool_count = sum(1 for t in _AI_TOOL_NAMES if t in tl)
    if tool_count >= 3:
        return _result(record, "rejected",
                       f"promotional content listing {tool_count} AI tools", "high")

    if any(p in tl for p in _PROMO_PHRASES) and tool_count >= 2:
        return _result(record, "rejected",
                       "promotional platform tweet with sign-up / try-it language", "medium")

    # ── reject: news / announcement ───────────────────────────────────────────
    if any(p in tl for p in _ANNOUNCEMENT_PHRASES):
        return _result(record, "rejected",
                       "news or announcement about GPT-image-2, not a generated image", "medium")

    # ── confirm: explicit creation language ───────────────────────────────────
    for phrase in _CREATION_PHRASES:
        if phrase in tl:
            return _result(record, "confirmed",
                           f"explicit creation language: '{phrase}'", "high")

    # ── confirm: prompt shared ────────────────────────────────────────────────
    if re.search(r"\bprompt\s*[:：]", text, re.IGNORECASE):
        return _result(record, "confirmed",
                       "tweet shares a generation prompt", "medium")

    # ── confirm: personal creation language ───────────────────────────────────
    for phrase in _PERSONAL_CREATION:
        if phrase in tl:
            return _result(record, "confirmed",
                           f"personal creation language: '{phrase}'", "medium")

    # ── confirm: AI art showcase hashtags ─────────────────────────────────────
    # People sharing their AI art creations reliably use these hashtags
    matched_tags = [tag for tag in _AIART_HASHTAGS if tag in tl]
    if matched_tags:
        return _result(record, "confirmed",
                       f"AI art showcase hashtags: {', '.join(matched_tags[:2])}", "medium")

    # ── uncertain: no clear signal ────────────────────────────────────────────
    return _result(record, "uncertain",
                   "no clear creation or rejection signals in tweet text", "low")


# ── stage 1: rule-based filter ────────────────────────────────────────────────

def load_metadata() -> list[dict]:
    records = []
    with METADATA_FILE.open() as f:
        for line in f:
            line = line.strip()
            if line:
                records.append(json.loads(line))
    return records


def quick_filter(records: list[dict]) -> tuple[list[dict], dict]:
    """Drop non-photos, failed downloads, and missing files. Returns (keep, stats)."""
    stats: dict[str, int] = {
        "total": len(records),
        "removed_media_type": 0,
        "removed_download_failed": 0,
        "removed_file_missing": 0,
    }
    keep = []
    for r in records:
        if r.get("media_type") != "photo":
            stats["removed_media_type"] += 1
            continue
        if not r.get("download_success"):
            stats["removed_download_failed"] += 1
            continue
        if not Path(r.get("local_path", "")).exists():
            stats["removed_file_missing"] += 1
            continue
        keep.append(r)
    return keep, stats


# ── classify & save ───────────────────────────────────────────────────────────

def classify_all(records: list[dict]) -> list[dict]:
    results = [classify_by_metadata(r) for r in records]
    with CURATED_FILE.open("w") as f:
        for rec in results:
            f.write(json.dumps(rec) + "\n")
    return results


# ── gemini vision review ──────────────────────────────────────────────────────

_GEMINI_MODEL = "gemini-2.5-flash"
_GEMINI_RPM = 15  # free-tier rate limit


def _gemini_classify_one(client, record: dict) -> dict:
    """Send one image to Gemini and return an updated record."""
    from PIL import Image

    path = Path(record["local_path"])
    img = Image.open(path)
    prompt = CLASSIFY_PROMPT.format(tweet_text=record.get("text", "")[:600])

    try:
        response = client.models.generate_content(
            model=_GEMINI_MODEL,
            contents=[prompt, img],
        )
        raw = response.text.strip()
        raw = re.sub(r"^```(?:json)?\s*|\s*```$", "", raw, flags=re.MULTILINE).strip()
        result = json.loads(raw)
        return {
            **record,
            "classification": result.get("label", "uncertain"),
            "classification_reason": result.get("reason", ""),
            "classification_confidence": result.get("confidence", "low"),
            "classified_at": datetime.now(timezone.utc).isoformat(),
            "classification_method": "gemini",
        }
    except Exception as exc:
        return {
            **record,
            "classification_method": "gemini_error",
            "gemini_error": str(exc)[:200],
        }


def gemini_review(api_key: str) -> None:
    """Reclassify all uncertain records using Gemini vision, update curated file."""
    from google import genai

    if not CURATED_FILE.exists():
        print("ERROR: Run classification first (no curated file found).")
        sys.exit(1)

    all_records = _load_curated()
    to_review = [
        r for r in all_records
        if r.get("classification") == "uncertain"
        and r.get("classification_method") != "gemini"
    ]

    if not to_review:
        print("No uncertain records left to review.")
        return

    eta_min = len(to_review) / _GEMINI_RPM
    print(f"Sending {len(to_review)} uncertain images to Gemini vision...")
    print(f"Rate limit: {_GEMINI_RPM} RPM  |  ETA: ~{eta_min:.1f} min")

    client = genai.Client(api_key=api_key)
    delay = 60.0 / _GEMINI_RPM  # seconds between requests

    key_fn = lambda r: (r["tweet_id"], r.get("media_key", ""))
    record_map = {key_fn(r): r for r in all_records}

    for i, record in enumerate(to_review):
        updated = _gemini_classify_one(client, record)
        record_map[key_fn(record)] = updated

        status = updated.get("classification", "error")
        reason = updated.get("classification_reason", updated.get("gemini_error", ""))[:70]
        print(f"  [{i+1:>3}/{len(to_review)}] {status:<12}  {reason}")

        # Save progress after every 10 records so a crash loses at most 10
        if (i + 1) % 10 == 0 or i + 1 == len(to_review):
            with CURATED_FILE.open("w") as f:
                for rec in record_map.values():
                    f.write(json.dumps(rec) + "\n")

        if i + 1 < len(to_review):
            time.sleep(delay)

    print(f"\nGemini review complete. Updated {CURATED_FILE}")


# ── report ────────────────────────────────────────────────────────────────────

def _load_curated() -> list[dict]:
    if not CURATED_FILE.exists():
        return []
    records = []
    with CURATED_FILE.open() as f:
        for line in f:
            line = line.strip()
            if line:
                records.append(json.loads(line))
    return records


def print_report(filter_stats: dict, classified: list[dict]) -> None:
    labels = Counter(r.get("classification") for r in classified)
    n = len(classified)

    passed = (
        filter_stats["total"]
        - filter_stats["removed_media_type"]
        - filter_stats["removed_download_failed"]
        - filter_stats["removed_file_missing"]
    )

    print("\n" + "=" * 54)
    print("    GPT-image-2 Dataset Curation Report")
    print("=" * 54)
    print(f"Records in metadata.jsonl:          {filter_stats['total']:>5}")
    print(f"  Removed (video / gif):            {filter_stats['removed_media_type']:>5}")
    print(f"  Removed (download failed):        {filter_stats['removed_download_failed']:>5}")
    print(f"  Removed (file missing on disk):   {filter_stats['removed_file_missing']:>5}")
    print(f"  Passed to classifier:             {passed:>5}")

    if not classified:
        print("\nNo classification results yet.")
        print("=" * 54 + "\n")
        return

    print(f"\nClassification results ({n} images):")
    for label in ("confirmed", "rejected", "uncertain"):
        count = labels.get(label, 0)
        pct = count / n * 100 if n else 0
        bar = "█" * int(pct / 2.5)
        print(f"  {label:<12} {count:>4}  ({pct:5.1f}%)  {bar}")

    print("\nTop rejection reasons:")
    reject_reasons = Counter(
        r.get("classification_reason", "")
        for r in classified
        if r.get("classification") == "rejected"
    )
    for reason, count in reject_reasons.most_common(8):
        print(f"  {count:>4}  {reason}")

    print("\nTop uncertain reasons:")
    uncertain_reasons = Counter(
        r.get("classification_reason", "")
        for r in classified
        if r.get("classification") == "uncertain"
    )
    for reason, count in uncertain_reasons.most_common(4):
        print(f"  {count:>4}  {reason}")

    confirmed_pct = labels.get("confirmed", 0) / n * 100 if n else 0
    total_useful = labels.get("confirmed", 0) + labels.get("uncertain", 0)
    print(f"\nYield summary:")
    print(f"  Confirmed GPT-image-2 images:        {labels.get('confirmed', 0):>4}  ({confirmed_pct:.1f}%)")
    print(f"  Confirmed + uncertain (upper bound):  {total_useful:>4}")

    methods = Counter(r.get("classification_method", "heuristic") for r in classified)
    if methods.get("gemini", 0) > 0:
        print(f"\nClassified by:")
        for method, count in methods.most_common():
            print(f"  {method:<16} {count:>4}")

    print(f"\nOutput: {CURATED_FILE}")
    print("=" * 54 + "\n")


def show_samples(classified: list[dict], label: str, n: int = 10) -> None:
    samples = [r for r in classified if r.get("classification") == label]
    print(f"\n── {label.upper()} samples ({len(samples)} total, showing {min(n, len(samples))}) ──\n")
    for r in samples[:n]:
        print(f"  [{r.get('classification_confidence', '?')}] {r.get('classification_reason', '')}")
        tweet = r.get("text", "").replace("\n", " ")[:120]
        print(f"  Tweet: {tweet}")
        print(f"  URL:   {r.get('tweet_url', '')}")
        print()


# ── main ──────────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Curate GPT-image-2 dataset using tweet metadata heuristics + Gemini vision"
    )
    parser.add_argument("--dry-run", action="store_true",
                        help="Stage-1 filter stats only, no classification")
    parser.add_argument("--report", action="store_true",
                        help="Print stats from existing curated file")
    parser.add_argument("--show", choices=["confirmed", "rejected", "uncertain"],
                        help="Print sample tweets for a label")
    parser.add_argument("--gemini-review", action="store_true",
                        help="Send uncertain images to Gemini vision for reclassification")
    parser.add_argument("--scrape-dir", type=Path, default=None,
                        help="Scrape output directory to curate (default: scrape_output)")
    args = parser.parse_args()

    if args.scrape_dir:
        _set_scrape_dir(args.scrape_dir)

    if not METADATA_FILE.exists():
        print(f"ERROR: {METADATA_FILE} not found. Run scrape_gpt_image2.py first, or pass --scrape-dir.")
        sys.exit(1)

    records = load_metadata()
    keep, filter_stats = quick_filter(records)

    if args.dry_run:
        print_report(filter_stats, [])
        return

    if args.gemini_review:
        from dotenv import load_dotenv
        load_dotenv()
        api_key = os.environ.get("GEMINI_API_KEY", "")
        if not api_key:
            print("ERROR: GEMINI_API_KEY not set in .env")
            sys.exit(1)
        gemini_review(api_key)
        print_report(filter_stats, _load_curated())
        return

    if args.report or args.show:
        classified = _load_curated()
        if not classified:
            print("No curated file found. Run without flags first.")
            sys.exit(1)
        if args.show:
            show_samples(classified, args.show)
        else:
            print_report(filter_stats, classified)
        return

    print(f"Classifying {len(keep)} images using metadata heuristics...")
    classified = classify_all(keep)
    print_report(filter_stats, classified)


if __name__ == "__main__":
    main()
