"""
Post-process scrape_output/metadata.jsonl using tweet metadata heuristics.
Classifies each record as genuine GPT-image-2 output or noise based on
tweet text patterns — no API calls, no cost.

Usage:
    python curate_dataset.py            # classify all, print report
    python curate_dataset.py --dry-run  # stage-1 filter stats only
    python curate_dataset.py --report   # stats from existing curated file
    python curate_dataset.py --show confirmed   # print sample confirmed tweets
    python curate_dataset.py --show rejected    # print sample rejected tweets
    python curate_dataset.py --show uncertain   # print sample uncertain tweets
"""

import argparse
import json
import os
import re
import sys
import time
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

SCRAPE_DIR = Path("scrape_output")
METADATA_FILE = SCRAPE_DIR / "metadata.jsonl"
CURATED_FILE = SCRAPE_DIR / "curated_metadata.jsonl"


def _set_scrape_dir(path: Path) -> None:
    global SCRAPE_DIR, METADATA_FILE, CURATED_FILE
    SCRAPE_DIR = path
    METADATA_FILE = path / "metadata.jsonl"
    CURATED_FILE = path / "curated_metadata.jsonl"

